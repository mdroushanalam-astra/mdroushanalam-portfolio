// Generate dates between Dec 2025 and Mar 2026
function generateDate(index: number, total: number): string {
  const start = new Date("2025-12-01T00:00:00Z").getTime();
  const end = new Date("2026-03-07T07:00:00Z").getTime();
  const range = end - start;
  // Distribute across the range with some randomness
  const base = start + (range * index) / total;
  const jitter = (Math.random() - 0.5) * (range / total) * 0.8;
  const ts = Math.min(Math.max(base + jitter, start), end);
  const d = new Date(ts);
  // Add random hours/minutes
  d.setHours(Math.floor(Math.random() * 24));
  d.setMinutes(Math.floor(Math.random() * 60));
  return d.toISOString();
}

